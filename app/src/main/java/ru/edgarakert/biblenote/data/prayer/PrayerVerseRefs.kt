package ru.edgarakert.biblenote.data.prayer

import ru.edgarakert.biblenote.data.bible.BibleReferenceParser

/**
 * Разбор и сборка поля «Стихи» редактора просьбы (задача 14.11).
 *
 * Нельзя резать ввод по запятой самостоятельно — это порча данных: `BibleReferenceParser`
 * понимает перечисление стихов внутри ОДНОЙ ссылки ("Быт 1:2,5" — стихи 2 и 5 одной и той же
 * ссылки, коммит f7f0d01). Наивный `split(",")` разрежет "Флп 4:6-7, Быт 1:2,5" на "Флп 4:6-7",
 * "Быт 1:2" и бессмысленное "5" — второй стих второй ссылки молча потеряется.
 *
 * Вместо этого поле целиком отдаётся парсеру, а результатом становится `displayText` каждой
 * найденной им ссылки. Текст, который парсер не распознал, отбрасывается молча — экран карточки
 * просьбы (14.10) всё равно показывает только разобранные ссылки, так что расхождения с исходным
 * вводом не видно.
 */
object PrayerVerseRefs {

    /**
     * Разбирает сырой ввод пользователя парсером [parser]. Дубликаты (та же ссылка дважды)
     * выбрасываются, порядок первого появления сохраняется. Нераспознанный текст пропадает.
     */
    fun fromInput(input: String, parser: BibleReferenceParser): List<String> {
        val seen = LinkedHashSet<String>()
        for (ref in parser.parse(input)) {
            seen.add(ref.displayText)
        }
        return seen.toList()
    }

    /** Обратная операция — заполняет поле при открытии существующей просьбы на редактирование. */
    fun toInput(refs: List<String>): String = refs.joinToString(", ")
}
