package ru.edgarakert.biblenote.data

/**
 * Куда вставлять текст, который приходит в заметку из шторки ссылки.
 *
 * Вынесено из экрана редактора отдельной чистой функцией по замечанию ревью: арифметика с
 * границами строк слишком легко ошибается на краях, чтобы жить внутри Compose-лямбды без тестов.
 */
object NoteTextInsertion {

    /**
     * Конец строки, в которой находится [index] — позиция для вставки текста стиха.
     *
     * Вставляем не сразу за ссылкой, а в конец её строки: у пользователя после ссылки может идти
     * своя мысль («Быт 2:14 — важная мысль»), и вставка вплотную разрезала бы фразу пополам.
     * [index] приводится к границам строки, поэтому функция безопасна при рассинхроне индексов.
     */
    fun lineEndAfter(content: String, index: Int): Int {
        val from = index.coerceIn(0, content.length)
        val newline = content.indexOf('\n', from)
        return if (newline < 0) content.length else newline
    }
}
